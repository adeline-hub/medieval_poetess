import pandas as pd
from scipy.cluster.hierarchy import linkage, dendrogram
from sklearn.preprocessing import MultiLabelBinarizer
from matplotlib import font_manager
import matplotlib.patches as patches

# 📌 Données simplifiées
poets = [
    {"name": "Dante Alighieri", "themes": ["amour", "religion", "politique"]},
    {"name": "Hildegarde von Bingen", "themes": ["mystique", "médecine", "musique", "religion"]},
    {"name": "Chrétien de Troyes", "themes": ["chevalerie", "amour", "courtoisie"]},
    {"name": "Ibn Hazm", "themes": ["amour", "philosophie", "religion"]},
    {"name": "Béroul", "themes": ["amour", "tragédie", "légende"]},
    {"name": "Marie de France", "themes": ["amour", "féérie", "courtoisie"]},
    {"name": "Guido Guinizelli", "themes": ["amour", "dolce stil novo", "philosophie"]},
]

# 📊 Transformation en DataFrame
df = pd.DataFrame(poets)

# 🔄 Encodage binaire des thèmes
mlb = MultiLabelBinarizer()
themes_encoded = mlb.fit_transform(df["themes"])
df_encoded = pd.DataFrame(themes_encoded, columns=mlb.classes_, index=df["name"])

# 🔗 Clustering hiérarchique
linked = linkage(df_encoded, method='ward')

# 🎨 Dendrogramme avec style médiéval
fig, ax = plt.subplots(figsize=(10, 6))

# 👑 Fond parchemin
ax.set_facecolor('#f7f1d3')
fig.patch.set_facecolor('#e8dbc5')
ax.add_patch(patches.Rectangle((0, 0), 1, 1, transform=ax.transAxes,
                               facecolor='#f7f1d3', edgecolor='#8b5e3c', linewidth=10))

# 📜 Titre style ancien
plt.title("Clustering des poètes médiévaux", fontsize=16, fontweight='bold', family='serif', color='#5c3a21')

# 🌿 Dendrogramme
dendrogram(linked,
           labels=df["name"].values,
           orientation='top',
           distance_sort='descending',
           show_leaf_counts=True,
           color_threshold=10,
           leaf_font_size=10)

# 🎭 Ornementation
plt.xticks(rotation=45, ha='right')
plt.tight_layout()
plt.subplots_adjust(top=0.88)

# 🖼️ Affichage
plt.show()

