from sklearn.cluster import KMeans
import plotly.express as px
import numpy as np

# Étape 1 : Clustering en fonction de l'intensité (scores)
kmeans = KMeans(n_clusters=3, random_state=42)
df_all['cluster'] = kmeans.fit_predict(df_all[['score']])

# Étape 2 : Analyse des clusters pour voir l'intensité moyenne de chaque émotion
cluster_summary = df_all.groupby(['cluster', 'label'])['score'].mean().reset_index()

# Trouver l'émotion la plus forte dans chaque cluster
dominant_emotion = cluster_summary.loc[cluster_summary.groupby('cluster')['score'].idxmax()]

# Affichage des résultats de clustering
fig = px.scatter(df_all,
                 x='line_number',
                 y='score',
                 color='label',
                 size_max=10,
                 color_discrete_map={emotion: color for emotion, color in zip(df_all['label'].unique(), px.colors.qualitative.Set2)},
                 title="Clusters d'intensité émotionnelle des poèmes",
                 hover_data=['poet'])

# Ajouter les clusters sur le graphique
fig.update_traces(marker=dict(size=10, opacity=0.6, line=dict(width=2, color='DarkSlateGrey')))

# Affichage de l'intensité émotionnelle par cluster
for cluster_num in dominant_emotion['cluster']:
    fig.add_annotation(
        x=cluster_num, y=dominant_emotion.loc[dominant_emotion['cluster'] == cluster_num, 'score'].values[0],
        text=f"Cluster {cluster_num}: {dominant_emotion.loc[dominant_emotion['cluster'] == cluster_num, 'label'].values[0]}",
        showarrow=True,
        arrowhead=2,
        font=dict(size=12, color='black'),
        align='center'
    )

fig.update_layout(
    xaxis_title="Numéro de vers",
    yaxis_title="Score émotionnel",
    legend_title="Emotions",
    template="plotly_white"
)

fig.show()

