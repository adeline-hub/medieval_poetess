translator = pipeline("translation", model="Helsinki-NLP/opus-mt-fr-en", device=-1)
emotion_model = pipeline("text-classification",
                         model="j-hartmann/emotion-english-distilroberta-base",
                         top_k=1,
                         device=-1)

def process_poem(path, poet_name):
    # charge et nettoie
    with open(path, 'r', encoding='utf-8') as f:
        text = f.read()
    # garder retours à la ligne et ponctuations choisies
    text = re.sub(r'[^\w\s,.\-:;!?«»\n]', '', text)
    lines = [l.strip() for l in text.split('\n') if l.strip()]

    data = []
    # batcher la traduction peut être plus rapide si nombreuses lignes
    translations = translator(lines, max_length=200, batch_size=8)
    en_lines = [t['translation_text'] for t in translations]

    for i, (fr, en) in enumerate(zip(lines, en_lines)):
        raw = emotion_model(en)
        first = raw[0]
        result = first[0] if isinstance(first, list) else first

        data.append({
            'poet': poet_name,
            'line_number': i,
            'fr_text': fr,
            'en_text': en,
            'label': result['label'],
            'score': result['score']
        })
    return pd.DataFrame(data)

